import { build } from "esbuild";
import { readFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const repoRoot = resolve(packageRoot, "../..");
const outfile = resolve(repoRoot, "supabase/functions/api/index.js");

const manifest = JSON.parse(
  await readFile(resolve(packageRoot, "package.json"), "utf8"),
);

/**
 * The Edge Function is deployed as one file. Our own sources are bundled into
 * it; third-party packages are not — they are rewritten to Deno's `npm:`
 * specifiers, pinned to the exact version this workspace resolved.
 *
 * Bundling them instead would mean teaching esbuild to emit `node:` prefixes
 * for every builtin `postgres` reaches for, and would ship a copy of each
 * library into a file Supabase already knows how to fetch.
 */
const denoSpecifiers = {
  name: "npm-specifiers",
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => {
      if (args.kind === "entry-point") return null;
      const isRelative = args.path.startsWith(".") || args.path.startsWith("/");
      if (isRelative) return null;

      // The domain is ours, so it is bundled rather than fetched.
      if (args.path.startsWith("@tor-now/")) return null;

      if (args.path.startsWith("node:")) {
        return { path: args.path, external: true };
      }

      const [scope, rest] = args.path.startsWith("@")
        ? [args.path.split("/").slice(0, 2).join("/"), args.path.split("/").slice(2).join("/")]
        : [args.path.split("/")[0], args.path.split("/").slice(1).join("/")];

      const range = manifest.dependencies[scope];
      if (range === undefined) {
        throw new Error(
          `"${args.path}" is imported but "${scope}" is not a declared dependency. ` +
            `Add it to services/api/package.json so the deployed bundle pins a version.`,
        );
      }
      const version = range.replace(/^[\^~]/, "");
      const subpath = rest.length > 0 ? `/${rest}` : "";
      return { path: `npm:${scope}@${version}${subpath}`, external: true };
    });
  },
};

await mkdir(dirname(outfile), { recursive: true });

const result = await build({
  entryPoints: [resolve(packageRoot, "index.ts")],
  outfile,
  bundle: true,
  format: "esm",
  target: "esnext",
  platform: "neutral",
  plugins: [denoSpecifiers],
  // The deployed file is an artifact; the source of truth is services/api/src,
  // which is where debugging happens. `keepNames` is the one concession: it
  // costs a few kilobytes and keeps runtime stack traces naming real functions.
  minify: true,
  keepNames: true,
  legalComments: "none",
  banner: {
    js: "// Generated by services/api/scripts/bundle.mjs — do not edit.\n// Source of truth: services/api/src\n",
  },
  metafile: true,
});

const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`bundled → ${outfile} (${(bytes / 1024).toFixed(1)} kB)`);
